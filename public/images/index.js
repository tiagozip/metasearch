(() => {
  const captcha = () => import("/s/captcha.js");
  const solveCaptcha = async () => (await captcha()).solveCaptcha();
  const refillPool = async () =>
    (await captcha()).refill({ force: true }).catch(() => false);
  const refillWhenLow = (results) => {
    if (results?.pow_low) captcha().then((m) => m.refillWhenIdle());
  };

  const safeUrl = (url) => {
    if (!url) return "#";
    try {
      const parsed = new URL(url);
      if (parsed.protocol === "http:" || parsed.protocol === "https:")
        return url;
    } catch {}
    return "#";
  };

  const readCookie = (name) => {
    try {
      const m = document.cookie.match(
        new RegExp(
          "(?:^|; )" +
            name.replace(/[.$?*|{}()[\]\\/+^]/g, "\\$&") +
            "=([^;]*)",
        ),
      );
      return m ? decodeURIComponent(m[1]) : null;
    } catch {
      return null;
    }
  };

  const writeCookie = (name, value) => {
    try {
      const oneYear = 60 * 60 * 24 * 365;
      document.cookie = `${name}=${encodeURIComponent(value)}; path=/; max-age=${oneYear}; SameSite=Lax`;
    } catch {}
  };

  let detailMode =
    readCookie("pref_images_detail") === "sidebar" ? "sidebar" : "bar";
  let transparentOnly = false;

  let allImages = [];
  let selectedIndex = -1;
  let detailPanel = null;
  let isLoading = false;
  let hasMoreResults = true;
  let pk = "__results_pk__";
  const currentQuery = new URLSearchParams(window.location.search).get("q");

  const AI_KEYWORDS = [
    "ai generated",
    "ai-generated",
    "ai art",
    "stable diffusion",
    "generated by",
    "midjourney",
    "ai image generator",
    "generated with ai",
    "images using ai",
    "generated from ai",
    "ai digital art",
  ];

  let aiBlocklist = null;
  const fetchBlocklist = async () => {
    try {
      const cachedList = localStorage.getItem("slop:cache");
      const cachedTimestamp = localStorage.getItem("slop:ts");

      if (cachedList && cachedTimestamp) {
        const age = Date.now() - parseInt(cachedTimestamp, 10);
        if (age < 24 * 60 * 60 * 1000) {
          return cachedList;
        }
      }

      const text = await (
        await fetch(
          "https://cdn.jsdelivr.net/gh/laylavish/uBlockOrigin-HUGE-AI-Blocklist@main/list_uBlacklist.txt",
        )
      ).text();

      localStorage.setItem("slop:cache", text);
      localStorage.setItem("slop:ts", Date.now().toString());

      return text;
    } catch {
      return localStorage.getItem("slop:cache") || "";
    }
  };

  const parseBlocklist = (text) => {
    const patterns = [];
    const lines = text.split("\n");

    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) continue;

      if (trimmed.startsWith("/") && trimmed.endsWith("/")) {
        try {
          const regexStr = trimmed.slice(1, -1);
          patterns.push({ type: "regex", pattern: new RegExp(regexStr, "i") });
        } catch {
          console.warn("Invalid regex pattern:", trimmed);
        }
      } else if (trimmed.includes("*")) {
        const regexStr = trimmed
          .replace(/\*:\/\//g, "https?://")
          .replace(/\*/g, ".*")
          .replace(/\./g, "\\.");
        try {
          patterns.push({ type: "glob", pattern: new RegExp(regexStr, "i") });
        } catch {
          console.warn("Invalid glob pattern:", trimmed);
        }
      } else {
        patterns.push({ type: "text", pattern: trimmed.toLowerCase() });
      }
    }

    return patterns;
  };

  const shouldBlockImage = (img) => {
    if (!aiBlocklist) return false;

    const hostname = img.meta_url?.hostname || "";
    const url = img.url || "";

    if (hostname.endsWith(".ai")) {
      return true;
    }

    for (const keyword of AI_KEYWORDS) {
      if (
        (img.title || "")
          .toLowerCase()
          .replaceAll(" ", "")
          .includes(keyword.replaceAll(" ", ""))
      ) {
        return true;
      }
    }

    for (const { type, pattern } of aiBlocklist) {
      if (type === "regex" || type === "glob") {
        if (pattern.test(url) || pattern.test(hostname)) {
          return true;
        }
      } else if (type === "text") {
        if (
          url.toLowerCase().includes(pattern) ||
          hostname.toLowerCase().includes(pattern)
        ) {
          return true;
        }
      }
    }

    return false;
  };

  const initBlocklist = async () => {
    try {
      const hideAiSlop = localStorage.getItem("config:hide_slop") === "true";
      if (!hideAiSlop) {
        aiBlocklist = null;
        return;
      }

      aiBlocklist = parseBlocklist(await fetchBlocklist());
    } catch {
      // firefox with cookies disabled errors out instead
      // of returning null. we have this catch to prevent
      // the whole page from erroring out in that case
    }
  };

  const motion = matchMedia("(prefers-reduced-motion: no-preference)");
  const easeOut =
    getComputedStyle(document.documentElement)
      .getPropertyValue("--ease-out")
      .trim() || "cubic-bezier(0.23, 1, 0.32, 1)";
  const easeDrawer = "cubic-bezier(0.32, 0.72, 0, 1)";
  let closingPanel = null;

  const svgIcon = (d) =>
    `<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke="currentColor" aria-hidden="true"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="${d}"/></svg>`;

  const itemFor = (index) =>
    document.querySelector(
      `#images-grid .image-item[data-image-index="${index}"]`,
    );

  const neighborIndex = (from, direction) => {
    const items = [
      ...document.querySelectorAll("#images-grid .image-item"),
    ].filter((el) => el.offsetParent);
    const pos = items.findIndex((el) => Number(el.dataset.imageIndex) === from);
    if (pos === -1) return -1;
    const next = items[pos + direction];
    return next ? Number(next.dataset.imageIndex) : -1;
  };

  const updateNavButtons = () => {
    if (!detailPanel) return;
    for (const btn of detailPanel.querySelectorAll("[data-nav]")) {
      btn.disabled = neighborIndex(selectedIndex, Number(btn.dataset.nav)) < 0;
    }
  };

  const createDetailPanel = () => {
    const panel = document.createElement("div");
    panel.className = "image-detail-panel";
    panel.setAttribute("role", "region");
    panel.setAttribute("aria-label", "image details");
    if (detailMode === "sidebar") panel.classList.add("sidebar-mode");

    const header = document.createElement("div");
    header.className = "image-detail-header";

    for (const [label, d, nav] of [
      ["previous image", "M15 19l-7-7 7-7", -1],
      ["next image", "M9 5l7 7-7 7", 1],
      ["close", "M6 18L18 6M6 6l12 12", 0],
    ]) {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.innerHTML = svgIcon(d);
      btn.title = label;
      btn.setAttribute("aria-label", label);
      if (nav) btn.dataset.nav = nav;
      btn.addEventListener("click", (e) => {
        e.stopPropagation();
        if (nav) navigateImage(nav);
        else closeDetailPanel();
      });
      header.append(btn);
    }

    panel.append(header);
    return panel;
  };

  const createDetailContent = (img, thumbImg) => {
    const width = img.properties?.width;
    const height = img.properties?.height;
    const fullUrl = img.properties?.url || img.thumbnail || "";
    const ratio =
      width && height
        ? width / height
        : thumbImg?.naturalWidth
          ? thumbImg.naturalWidth / thumbImg.naturalHeight
          : 1;

    const content = document.createElement("div");
    content.className = "image-detail-content";

    const preview = document.createElement("a");
    preview.className = "image-detail-preview";
    preview.href = safeUrl(fullUrl);
    preview.target = "_blank";
    preview.rel = "noopener";

    const previewImg = document.createElement("img");
    previewImg.alt = img.title || "";
    previewImg.style.setProperty("--ar", ratio);
    if (img.thumbnail) {
      previewImg.style.backgroundImage = `url(${JSON.stringify(img.thumbnail)})`;
    }
    previewImg.src = `https://external-content.duckduckgo.com/iu/?u=${encodeURIComponent(fullUrl)}`;
    preview.append(previewImg);

    const info = document.createElement("div");
    info.className = "image-detail-info";

    const titleEl = document.createElement("h2");
    titleEl.className = "image-detail-title";
    titleEl.textContent = img.title || "";

    const sourceEl = document.createElement("a");
    sourceEl.className = "image-detail-source";
    sourceEl.href = safeUrl(img.url);
    sourceEl.target = "_blank";
    sourceEl.rel = "noopener";
    if (img.meta_url?.favicon) {
      const favicon = document.createElement("img");
      favicon.src = img.meta_url.favicon;
      favicon.alt = "";
      favicon.onerror = () => favicon.remove();
      sourceEl.append(favicon);
    }
    const sourceName = document.createElement("span");
    sourceName.textContent = (img.meta_url?.hostname || "").replace(
      /^www\./,
      "",
    );
    sourceEl.append(sourceName);

    info.append(titleEl, sourceEl);

    if (width && height) {
      const dimensionsEl = document.createElement("div");
      dimensionsEl.className = "image-detail-dimensions";
      dimensionsEl.textContent = `${width} × ${height}`;
      info.append(dimensionsEl);
    }

    const actions = document.createElement("div");
    actions.className = "image-detail-actions";
    const viewLink = document.createElement("a");
    viewLink.href = safeUrl(fullUrl);
    viewLink.target = "_blank";
    viewLink.rel = "noopener";
    viewLink.innerHTML = `<span>view file</span>${svgIcon("M7 17L17 7M8 7h9v9")}`;
    actions.append(viewLink);
    info.append(actions);

    content.append(preview, info);
    return content;
  };

  const flipFromThumb = (thumb, target) => {
    if (!thumb) return;
    const from = thumb.getBoundingClientRect();
    const to = target.getBoundingClientRect();
    if (!from.width || !to.width || !to.height) return;
    const scale = Math.max(from.width / to.width, from.height / to.height);
    const dx = from.left + from.width / 2 - (to.left + to.width / 2);
    const dy = from.top + from.height / 2 - (to.top + to.height / 2);
    const insetX = Math.max(0, (to.width - from.width / scale) / 2);
    const insetY = Math.max(0, (to.height - from.height / scale) / 2);
    const keyframes = [
      {
        transform: `translate(${dx}px, ${dy}px) scale(${scale})`,
        clipPath: `inset(${insetY}px ${insetX}px round ${10 / scale}px)`,
      },
      { transform: "none", clipPath: "inset(0px 0px round 10px)" },
    ];
    const timing = { duration: 460, easing: easeDrawer };

    if (!target.closest(".sidebar-mode")) {
      target.animate(keyframes, timing);
      return;
    }

    const ghost = document.createElement("img");
    ghost.src = thumb.currentSrc || thumb.src;
    ghost.alt = "";
    Object.assign(ghost.style, {
      position: "fixed",
      left: `${to.left}px`,
      top: `${to.top}px`,
      width: `${to.width}px`,
      height: `${to.height}px`,
      objectFit: "cover",
      borderRadius: "10px",
      zIndex: 60,
      pointerEvents: "none",
    });
    document.body.append(ghost);
    target.style.visibility = "hidden";
    const done = () => {
      ghost.remove();
      target.style.visibility = "";
    };
    ghost.animate(keyframes, timing).finished.then(done, done);
  };

  const slideContent = (content, direction) => {
    const offset = direction * 16;
    for (const el of [
      content.querySelector(".image-detail-preview img"),
      content.querySelector(".image-detail-info"),
    ]) {
      el?.animate(
        [
          { opacity: 0, transform: `translateX(${offset}px)` },
          { opacity: 1, transform: "none" },
        ],
        { duration: 200, easing: easeOut },
      );
    }
  };

  const clipWhile = (panel, animation) => {
    panel.classList.add("is-animating");
    animation.finished
      .catch(() => {})
      .then(() => panel.classList.remove("is-animating"));
  };

  const preserveAnchorPosition = (anchor, mutate) => {
    if (!anchor) {
      mutate();
      return;
    }
    const before = anchor.getBoundingClientRect().top;
    mutate();
    const after = anchor.getBoundingClientRect().top;
    const delta = after - before;
    if (delta) {
      window.scrollBy({ top: delta, left: 0, behavior: "instant" });
    }
  };

  const closeDetailPanel = ({ instant = false } = {}) => {
    const selected = document.querySelector(".image-item.selected");
    selected?.classList.remove("selected");
    selectedIndex = -1;

    const panel = detailPanel;
    detailPanel = null;
    if (!panel) return;

    const hadFocus = panel.contains(document.activeElement);
    const sidebar = panel.classList.contains("sidebar-mode");
    if (sidebar) {
      preserveAnchorPosition(selected, () =>
        document.body.classList.remove("images-detail-sidebar-open"),
      );
    }
    if (hadFocus) selected?.focus({ preventScroll: true });

    if (instant || !motion.matches || !panel.isConnected) {
      panel.remove();
      return;
    }

    closingPanel?.remove();
    closingPanel = panel;
    panel.style.pointerEvents = "none";
    const done = () => {
      panel.remove();
      if (closingPanel === panel) closingPanel = null;
    };

    if (sidebar) {
      panel
        .animate(
          [
            { opacity: 1, transform: "none", filter: "blur(0px)" },
            { opacity: 0, transform: "translateX(12px)", filter: "blur(4px)" },
          ],
          { duration: 180, easing: easeOut, fill: "forwards" },
        )
        .finished.then(done, done);
      return;
    }

    const content = panel.querySelector(".image-detail-content");
    content?.animate([{ opacity: 1 }, { opacity: 0 }], {
      duration: 120,
      easing: "ease-out",
      fill: "forwards",
    });
    const shrink = panel.animate(
      [
        { height: `${panel.offsetHeight}px` },
        { height: "0px", marginTop: "0px", marginBottom: "0px" },
      ],
      { duration: 260, easing: easeOut, fill: "forwards" },
    );
    for (const pseudoElement of ["::before", "::after"]) {
      panel.animate(
        [{ transform: "none" }, { transform: "translateY(20px)" }],
        {
          duration: 260,
          easing: easeOut,
          fill: "forwards",
          pseudoElement,
        },
      );
    }
    panel.classList.add("is-animating");
    shrink.finished.then(done, done);
  };

  const showDetailPanel = (index, { direction = 0 } = {}) => {
    const item = itemFor(index);
    const img = allImages[index];
    if (!item || !img) return;

    closingPanel?.remove();
    closingPanel = null;

    document
      .querySelector(".image-item.selected")
      ?.classList.remove("selected");
    item.classList.add("selected");
    selectedIndex = index;
    if (document.activeElement?.classList.contains("image-item")) {
      item.focus({ preventScroll: true });
    }

    const thumbImg = item.querySelector("img");
    const content = createDetailContent(img, thumbImg);
    const animate = motion.matches;
    const fromThumb = !direction;

    const swapInto = (panel) => {
      const sidebar = panel.classList.contains("sidebar-mode");
      const before = panel.offsetHeight;
      panel.querySelector(".image-detail-content").replaceWith(content);
      updateNavButtons();
      if (sidebar) {
        item.scrollIntoView({
          block: "nearest",
          behavior: animate ? "smooth" : "auto",
        });
      }
      if (!animate) return;
      const after = panel.offsetHeight;
      if (!sidebar && before !== after) {
        clipWhile(
          panel,
          panel.animate([{ height: `${before}px` }, { height: `${after}px` }], {
            duration: 280,
            easing: easeOut,
          }),
        );
      }
      if (fromThumb)
        flipFromThumb(
          thumbImg,
          content.querySelector(".image-detail-preview img"),
        );
      else slideContent(content, direction);
    };

    if (detailMode === "sidebar") {
      if (detailPanel) {
        swapInto(detailPanel);
        return;
      }
      detailPanel = createDetailPanel();
      detailPanel.append(content);
      preserveAnchorPosition(item, () => {
        document.body.classList.add("images-detail-sidebar-open");
        document.body.append(detailPanel);
      });
      updateNavButtons();
      if (!animate) return;
      const target = content.querySelector(".image-detail-preview img");
      if (fromThumb) flipFromThumb(thumbImg, target);
      detailPanel.animate(
        [
          { opacity: 0, transform: "translateX(24px)" },
          { opacity: 1, transform: "none" },
        ],
        { duration: 320, easing: easeOut },
      );
      return;
    }

    const rowEnd = () => {
      let end = item;
      for (let el = item.nextElementSibling; el; el = el.nextElementSibling) {
        if (!el.classList.contains("image-item")) break;
        if (!el.offsetParent) continue;
        if (Math.abs(el.offsetTop - item.offsetTop) >= 10) break;
        end = el;
      }
      return end;
    };

    if (
      detailPanel?.isConnected &&
      rowEnd().nextElementSibling === detailPanel
    ) {
      swapInto(detailPanel);
      return;
    }

    if (detailPanel) {
      const old = detailPanel;
      detailPanel = null;
      preserveAnchorPosition(item, () => old.remove());
    }

    const panel = createDetailPanel();
    panel.append(content);
    rowEnd().after(panel);
    detailPanel = panel;
    updateNavButtons();

    const rect = panel.getBoundingClientRect();
    const itemTop = item.getBoundingClientRect().top;
    const overflow = rect.bottom + 16 - window.innerHeight;
    const delta =
      itemTop < 16
        ? itemTop - 16
        : Math.max(0, Math.min(overflow, itemTop - 16));
    if (delta) {
      window.scrollBy({ top: delta, behavior: animate ? "smooth" : "auto" });
    }

    if (!animate) return;

    if (!fromThumb) {
      slideContent(content, direction);
      return;
    }

    const opts = { duration: 460, easing: easeDrawer };
    clipWhile(
      panel,
      panel.animate(
        [
          { height: "0px", marginTop: "0px", marginBottom: "0px" },
          {
            height: `${rect.height}px`,
            marginTop: "12px",
            marginBottom: "12px",
          },
        ],
        opts,
      ),
    );
    for (const pseudoElement of ["::before", "::after"]) {
      panel.animate(
        [{ transform: "translateY(20px)" }, { transform: "none" }],
        {
          ...opts,
          pseudoElement,
        },
      );
    }
    panel
      .querySelector(".image-detail-header")
      .animate([{ opacity: 0 }, { opacity: 1 }], {
        duration: 240,
        delay: 120,
        easing: easeOut,
        fill: "backwards",
      });
    flipFromThumb(thumbImg, content.querySelector(".image-detail-preview img"));
  };

  const navigateImage = (direction) => {
    const next = neighborIndex(selectedIndex, direction);
    if (next >= 0) showDetailPanel(next, { direction });
  };

  const transparencyCanvas = document.createElement("canvas");
  transparencyCanvas.width = 48;
  transparencyCanvas.height = 48;
  const transparencyCtx = transparencyCanvas.getContext("2d", {
    willReadFrequently: true,
  });

  const detectTransparent = (imgEl) => {
    try {
      transparencyCtx.clearRect(0, 0, 48, 48);
      transparencyCtx.drawImage(imgEl, 0, 0, 48, 48);
      const { data } = transparencyCtx.getImageData(0, 0, 48, 48);
      let transparent = 0;
      for (let i = 3; i < data.length; i += 4) {
        if (data[i] < 250) transparent++;
      }
      return transparent / (data.length / 4) > 0.01;
    } catch {
      return null;
    }
  };

  const applyTransparentFilter = (link, imgEl, img) => {
    if (imgEl.complete && !imgEl.naturalWidth) return;

    if (!transparentOnly) {
      if (link.dataset.transHidden) {
        delete link.dataset.transHidden;
        link.style.display = "";
      }
      return;
    }

    if (!imgEl.complete) {
      link.dataset.transHidden = "1";
      link.style.display = "none";
      return;
    }

    if (img._transparent === undefined)
      img._transparent = detectTransparent(imgEl);

    if (img._transparent === true) {
      if (link.dataset.transHidden) {
        delete link.dataset.transHidden;
        link.style.display = "";
      }
    } else {
      link.dataset.transHidden = "1";
      link.style.display = "none";
    }
  };

  const reapplyTransparentFilter = () => {
    const grid = document.getElementById("images-grid");
    for (const link of grid.querySelectorAll(".image-item")) {
      const img = allImages[parseInt(link.dataset.imageIndex, 10)];
      const imgEl = link.querySelector("img");
      if (img && imgEl) applyTransparentFilter(link, imgEl, img);
    }
  };

  const renderImageResult = (img, index) => {
    if (shouldBlockImage(img)) {
      return null;
    }

    const thumbUrl = img.thumbnail || img.properties?.url || "";
    const title = img.title || "";
    const hostname = img.meta_url?.hostname || "";
    const favicon = img.meta_url?.favicon || "";
    const sourceName = hostname.replace(/^www\./, "").split("/")[0];
    const width = img.properties?.width;
    const height = img.properties?.height;

    const link = document.createElement("div");
    link.className = "image-item";
    link.tabIndex = 0;
    link.setAttribute("role", "button");
    link.setAttribute("aria-label", title || "image");
    link.dataset.imageIndex = index;

    const imageWrapper = document.createElement("div");
    imageWrapper.className = "image-wrapper";

    const imgEl = document.createElement("img");
    imgEl.alt = title;
    imgEl.loading = "lazy";
    if (thumbUrl.startsWith("https://imgs.search.brave.com/")) {
      imgEl.crossOrigin = "anonymous";
    }
    imgEl.onload = () => {
      link.classList.add("loaded");
      applyTransparentFilter(link, imgEl, img);
    };
    imgEl.onerror = () => {
      link.style.display = "none";
    };
    imgEl.src = thumbUrl;

    if (width && height) {
      const aspectRatio = width / height;
      const itemWidth = Math.round(180 * aspectRatio);
      link.style.flexBasis = `${itemWidth}px`;
    }

    imageWrapper.append(imgEl);

    const infoDiv = document.createElement("div");
    infoDiv.className = "image-info";

    const titleDiv = document.createElement("div");
    titleDiv.className = "image-title";
    titleDiv.textContent = title;
    infoDiv.append(titleDiv);

    const sourceDiv = document.createElement("div");
    sourceDiv.className = "image-source";

    if (favicon) {
      const faviconImg = document.createElement("img");
      faviconImg.className = "favicon";
      faviconImg.src = favicon;
      faviconImg.alt = "";
      faviconImg.onerror = () => {
        faviconImg.style.display = "none";
      };
      sourceDiv.append(faviconImg);
    }

    if (sourceName) {
      const sourceNameSpan = document.createElement("span");
      sourceNameSpan.className = "source-name";
      sourceNameSpan.textContent = sourceName;
      sourceDiv.append(sourceNameSpan);
    }

    infoDiv.append(sourceDiv);

    link.append(imageWrapper);
    link.append(infoDiv);

    link.addEventListener("click", (e) => {
      e.preventDefault();
      if (selectedIndex === index) closeDetailPanel();
      else showDetailPanel(index);
    });

    link.addEventListener("keydown", (e) => {
      if (e.key !== "Enter" && e.key !== " ") return;
      e.preventDefault();
      link.click();
    });

    return link;
  };

  const renderImages = (results) => {
    const grid = document.getElementById("images-grid");
    const frag = document.createDocumentFragment();

    if (!results?.length) {
      const noResults = document.createElement("div");
      noResults.className = "no-results";
      noResults.textContent = "no images found";
      frag.append(noResults);
    } else {
      allImages = results;
      for (let i = 0; i < results.length; i++) {
        const element = renderImageResult(results[i], i);
        if (element) frag.append(element);
      }
    }

    grid.append(frag);
  };

  const appendImages = (results) => {
    const grid = document.getElementById("images-grid");
    const frag = document.createDocumentFragment();
    const startIndex = allImages.length;

    for (let i = 0; i < results.length; i++) {
      allImages.push(results[i]);
      const element = renderImageResult(results[i], startIndex + i);
      if (element) frag.append(element);
    }

    grid.append(frag);
  };

  const loadMoreImages = async () => {
    if (isLoading || !hasMoreResults || !currentQuery) return;
    isLoading = true;
    const loadingEl = document.getElementById("loading-indicator");
    loadingEl.classList.add("visible");

    try {
      const res = await fetch("/p", {
        method: "POST",
        headers: {
          "X-Galileo-Hash": [...`${currentQuery}${pk}`]
            .reduce((h, c) => (h * 31 + c.charCodeAt(0)) | 0, 0)
            .toString(16),
          "X-Galileo-JWT": "__results_cl__",
          "X-Galileo-Pass": "%%galileo_pass%%",
        },
        body: pk,
      });

      pk = res.headers.get("x-galileo-upk") || pk;
      const newData = await res.json();

      if (newData.pow_required) {
        if (await refillPool()) setTimeout(loadMoreImages);
        else hasMoreResults = false;
        return;
      }
      refillWhenLow(newData);

      if (newData.error || !newData.results?.length) {
        hasMoreResults = false;
        loadingEl.classList.remove("visible");
        if (!newData.results?.length) {
          const endEl = document.createElement("div");
          endEl.className = "end-of-results";
          endEl.textContent = "no more images";
          document.getElementById("images-grid").append(endEl);
        }
        return;
      }

      appendImages(newData.results);
      hasMoreResults =
        newData.more_results_available !== false && newData.results.length > 0;
    } catch (err) {
      console.error("failed to load more images:", err);
    } finally {
      isLoading = false;
      if (document.getElementById("loading-indicator")) {
        document
          .getElementById("loading-indicator")
          .classList.remove("visible");
      }
    }
  };

  document.addEventListener("keydown", (e) => {
    if (selectedIndex === -1) return;
    if (e.target.closest?.("input, textarea, [contenteditable]")) return;

    if (e.key === "Escape") {
      closeDetailPanel();
    } else if (e.key === "ArrowLeft") {
      e.preventDefault();
      navigateImage(-1);
    } else if (e.key === "ArrowRight") {
      e.preventDefault();
      navigateImage(1);
    }
  });

  const optionsBtn = document.querySelector("#options-btn");
  const optionsPopup = document.querySelector("#options-popup");
  const hideAiSlopCheckbox = document.querySelector("#hide-ai-slop");
  const detailsSidebarCheckbox = document.querySelector("#details-sidebar");
  const transparentOnlyCheckbox = document.querySelector("#transparent-only");

  let savedSetting;
  try {
    savedSetting = localStorage.getItem("config:hide_slop") === "true";
    transparentOnly =
      localStorage.getItem("config:transparent_only") === "true";
  } catch {}

  hideAiSlopCheckbox.checked = savedSetting;
  if (detailsSidebarCheckbox)
    detailsSidebarCheckbox.checked = detailMode === "sidebar";
  if (transparentOnlyCheckbox)
    transparentOnlyCheckbox.checked = transparentOnly;

  optionsBtn?.addEventListener("click", (e) => {
    e.stopPropagation();
    optionsPopup.classList.toggle("visible");
  });

  document.addEventListener("mousedown", (e) => {
    if (!optionsPopup.contains(e.target) && e.target !== optionsBtn) {
      optionsPopup.classList.remove("visible");
    }
  });

  hideAiSlopCheckbox?.addEventListener("change", async (e) => {
    const isEnabled = e.target.checked;
    localStorage.setItem("config:hide_slop", isEnabled.toString());

    await initBlocklist();

    closeDetailPanel({ instant: true });
    const grid = document.getElementById("images-grid");
    grid.innerHTML = "";
    renderImages(allImages);
  });

  transparentOnlyCheckbox?.addEventListener("change", (e) => {
    transparentOnly = e.target.checked;
    try {
      localStorage.setItem(
        "config:transparent_only",
        transparentOnly.toString(),
      );
    } catch {}
    reapplyTransparentFilter();
  });

  detailsSidebarCheckbox?.addEventListener("change", (e) => {
    const wasOpen = selectedIndex !== -1;
    const reopenIndex = selectedIndex;

    if (wasOpen) closeDetailPanel({ instant: true });

    detailMode = e.target.checked ? "sidebar" : "bar";
    writeCookie("pref_images_detail", detailMode);

    if (wasOpen) showDetailPanel(reopenIndex);
  });

  (async () => {
    await initBlocklist();

    const data = __results_template__;
    hasMoreResults = data.more_results_available !== false;
    refillWhenLow(data);

    if (data.pow_required) {
      solveCaptcha().then(() => {
        location.reload();
      });
      return;
    }

    renderImages(data.results);

    const observer = new IntersectionObserver(
      (entries) => {
        if (entries[0].isIntersecting) {
          loadMoreImages();
        }
      },
      {
        rootMargin: "400px",
      },
    );

    observer.observe(document.querySelector("#load-more-sentinel"));
  })();

  document.addEventListener("keydown", (event) => {
    const input = document.querySelector(".search-bar input");
    if (document.activeElement === input) return;

    if (event.key === "/") {
      input.focus();
      input.setSelectionRange(input.value.length, input.value.length);
      event.preventDefault();
    }

    if (event.key === "w") {
      document.querySelectorAll(".tabs .tab")[0].click();
    }

    if (event.key === "i") {
      document.querySelectorAll(".tabs .tab")[1].click();
    }

    if (event.key === "n") {
      document.querySelectorAll(".tabs .tab")[2].click();
    }
  });
})();
